#!/usr/bin/env python3
"""Generate, validate, install, and measure the portable iOS instruction bundle.

Python 3.11+. Generation/validation/installation need only the standard library.
Token counts optionally use tiktoken with an explicitly selected proxy encoding.
"""

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
COLORS = {
    "architecture": "green", "devops": "cyan", "performance": "orange",
    "security": "red", "swift": "yellow", "swiftui": "blue", "testing": "purple",
}
COMMANDS = (
    "accessibility", "analyze", "brainstorm", "cleanup", "design", "document",
    "implement", "improve", "localize", "migrate", "optimize", "publish",
    "security", "test", "troubleshoot",
)
NOTICE = "<!-- Generated by scripts/framework.py; edit the source skill instead. -->\n\n"


def markdown(path):
    """Read our flat YAML string metadata (JSON-quoted or plain scalar values)."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: missing frontmatter")
    header, body = text[4:].split("\n---\n", 1)
    fields = {}
    for line in header.splitlines():
        key, value = line.split(":", 1)
        value = value.strip()
        if key in fields or not value:
            raise ValueError(f"{path}: duplicate/empty metadata: {key}")
        fields[key] = json.loads(value) if value.startswith('"') else value
    if not fields.get("description") or not body.strip():
        raise ValueError(f"{path}: description/body required")
    return fields, body.strip() + "\n"


def generated_files():
    files = {}
    for domain, color in COLORS.items():
        source = ROOT / "skills" / f"ios-{domain}" / "SKILL.md"
        meta, body = markdown(source)
        name = f"{domain}-specialist"
        if meta.get("name") != f"ios-{domain}":
            raise ValueError(f"{source}: name must match skill folder")
        fields = {"name": name, "description": meta["description"],
                  "model": "inherit", "color": color}
        header = "\n".join(f"{key}: {json.dumps(value)}" for key, value in fields.items())
        files[Path("agents") / f"{name}.md"] = f"---\n{header}\n---\n\n{NOTICE}{body}"
        # JSON basic strings are valid TOML basic strings; no runtime file lookup.
        fields = {"name": name, "description": meta["description"],
                  "developer_instructions": body}
        files[Path("codex/agents") / f"{name}.toml"] = (
            "# Generated by scripts/framework.py; edit the source skill instead.\n"
            + "\n".join(f"{key} = {json.dumps(value)}" for key, value in fields.items()) + "\n"
        )
    for name in COMMANDS:
        _, body = markdown(ROOT / "commands" / f"{name}.md")
        files[Path("skills/ios-workflow/references") / f"{name}.md"] = (
            "<!-- Generated from commands/ by scripts/framework.py. -->\n\n" + body
        )
    return files


def generate():
    for relative, content in generated_files().items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print("Generated 7 Claude agents, 7 Codex agents, and 15 workflow references.")


def check():
    expected = generated_files()
    for relative, content in expected.items():
        path = ROOT / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise ValueError(f"{relative}: missing/stale; run python3 scripts/framework.py generate")
    skills = sorted((ROOT / "skills").glob("*/SKILL.md"))
    if len(skills) != 8:
        raise ValueError("Expected 7 specialist skills and 1 workflow skill")
    for path in skills:
        meta, body = markdown(path)
        if meta.get("name") != path.parent.name or not re.fullmatch(r"[a-z0-9-]{1,64}", meta["name"]):
            raise ValueError(f"{path}: invalid skill name")
        if len(meta["description"]) > 320 or len(body.split()) > 500:
            raise ValueError(f"{path}: discovery/body budget exceeded")
        if "TODO" in body or "[insert" in body.lower():
            raise ValueError(f"{path}: unfinished template")
    for path in (ROOT / "codex/agents").glob("*.toml"):
        fields = tomllib.loads(path.read_text(encoding="utf-8"))
        if set(fields) != {"name", "description", "developer_instructions"}:
            raise ValueError(f"{path}: unexpected Codex agent fields")
    marketplace = json.loads((ROOT / ".claude-plugin/marketplace.json").read_text())
    plugin = marketplace["plugins"][0]
    for kind in ("agents", "commands"):
        listed = {Path(p) for p in plugin[kind]}
        actual = {p.relative_to(ROOT) for p in (ROOT / kind).glob("*.md")}
        if listed != actual:
            raise ValueError(f"Marketplace {kind} do not match files")
    json.loads((ROOT / "hooks/hooks.json").read_text())
    # Distributed Markdown must work without ignored local docs or audit files.
    paths = [ROOT / "README.md", ROOT / "AGENTS.md", ROOT / "CLAUDE.md",
             *ROOT.glob(".claude/*.md"), *ROOT.glob("examples/**/*.md"),
             *ROOT.glob("skills/**/*.md")]
    for path in paths:
        for target in re.findall(r"\]\(([^)]+)\)", path.read_text(encoding="utf-8")):
            if "://" in target or target.startswith("#"):
                continue
            if not (path.parent / target.split("#")[0]).exists():
                raise ValueError(f"{path}: broken local link: {target}")
    print("Bundle valid: 8 skills, 7 agents per client, 15 workflows; generated files match sources.")


def install(project, with_agents=False):
    """Copy only bundled files; preflight all conflicts before writing anything."""
    check()
    project = project.expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"Project directory does not exist: {project}")
    files = {}
    for path in (ROOT / "skills").rglob("*"):
        if path.is_file():
            files[project / ".agents/skills" / path.relative_to(ROOT / "skills")] = path.read_bytes()
    if with_agents:
        for path in (ROOT / "codex/agents").glob("*.toml"):
            files[project / ".codex/agents" / path.name] = path.read_bytes()
    for path, data in files.items():
        # Reject symlink destinations/parents, including broken symlinks.
        for parent in (path, *path.parents):
            if parent == project:
                break
            if parent.is_symlink():
                raise ValueError(f"Refusing symlink destination: {parent}")
            if parent != path and parent.exists() and not parent.is_dir():
                raise ValueError(f"Destination parent is not a directory: {parent}")
        if path.exists() and (not path.is_file() or path.read_bytes() != data):
            raise ValueError(f"Existing file differs; compare before replacing: {path}")
    count = 0
    for path, data in files.items():
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            count += 1
    print(f"Installed {count} new files into {project}; existing identical files preserved.")


def budget(tokens=False):
    groups = {
        "agents": sorted((ROOT / "agents").glob("*.md")),
        "commands": sorted((ROOT / "commands").glob("*.md")),
        "core": [ROOT / "AGENTS.md", ROOT / "CLAUDE.md", *sorted((ROOT / ".claude").glob("*.md"))],
        "skills": sorted((ROOT / "skills").glob("*/SKILL.md")),
        "codex_agents": sorted((ROOT / "codex/agents").glob("*.toml")),
    }
    encode = None
    if tokens:
        import tiktoken  # Optional: may download the public dictionary on first use.
        encode = tiktoken.get_encoding("o200k_base").encode
    report = {"encoding": "o200k_base (proxy, not billed usage)" if tokens else None, "groups": {}}
    baseline_path = ROOT / "docs/audit-baseline.json"
    baseline = json.loads(baseline_path.read_text())["groups"] if baseline_path.is_file() else {}
    for name, paths in groups.items():
        texts = [path.read_text(encoding="utf-8") for path in paths]
        data = {"files": len(paths), "words": sum(len(text.split()) for text in texts)}
        if encode:
            data["tokens"] = sum(len(encode(text)) for text in texts)
            if name in baseline:
                data["baseline_tokens"] = baseline[name]["tokens"]
                data["reduction_percent"] = round(100 * (1 - data["tokens"] / baseline[name]["tokens"]), 1)
        report["groups"][name] = data
    descriptions = [markdown(path)[0] for path in groups["skills"]]
    discovery = "\n".join(f'{item["name"]}: {item["description"]}' for item in descriptions)
    report["skill_discovery"] = {"characters": len(discovery), "words": len(discovery.split())}
    if encode:
        report["skill_discovery"]["tokens"] = len(encode(discovery))
    print(json.dumps(report, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    commands.add_parser("generate")
    commands.add_parser("check")
    install_parser = commands.add_parser("install-codex")
    install_parser.add_argument("--project", required=True, type=Path)
    install_parser.add_argument("--with-agents", action="store_true")
    budget_parser = commands.add_parser("budget")
    budget_parser.add_argument("--tokens", action="store_true")
    args = parser.parse_args()
    try:
        if args.action == "generate":
            generate()
        elif args.action == "check":
            check()
        elif args.action == "install-codex":
            install(args.project, args.with_agents)
        else:
            budget(args.tokens)
    except (ValueError, OSError, ImportError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
